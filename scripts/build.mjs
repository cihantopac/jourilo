#!/usr/bin/env node
// Bundles the Jourilo CLI into plugin/dist/jourilo.mjs. dist/ is committed so the Claude Code plugin works right
// after install. playwright-core stays external (it ships browser drivers and must be installed with npm);
// axe-core is bundled. The TypeScript parser (TypeScript 6, the `typescript-js` alias) is bundled into its own chunk,
// plugin/dist/ts-parser.mjs, which jourilo.mjs loads with import() only when a repository has code routes.
import { mkdirSync, readFileSync, rmSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outdir = process.argv[2] ? resolve(process.cwd(), process.argv[2]) : join(root, 'plugin', 'dist');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

/** `import x from './file.js?raw'` → the file's text (same convention Vite/Vitest use). */
const rawPlugin = {
  name: 'raw',
  setup(b) {
    // Paths stay relative to the repository so the bundle is identical on every machine (and leaks no home dir).
    b.onResolve({ filter: /\?raw$/ }, (args) => ({
      path: relative(root, resolve(args.resolveDir, args.path.replace(/\?raw$/, '')))
        .split(sep)
        .join('/'),
      namespace: 'raw',
    }));
    b.onLoad({ filter: /.*/, namespace: 'raw' }, (args) => ({
      contents: readFileSync(join(root, args.path), 'utf8'),
      loader: 'text',
    }));
  },
};

/** load.ts's `import('./parser.js')` → the separate chunk next to jourilo.mjs (never bundled into it). */
const tsParserChunk = {
  name: 'ts-parser-chunk',
  setup(b) {
    b.onResolve({ filter: /^\.\/parser\.js$/ }, (args) =>
      args.importer.endsWith(join('src', 'discovery', 'ast', 'load.ts'))
        ? { path: './ts-parser.mjs', external: true }
        : undefined,
    );
  },
};

rmSync(outdir, { recursive: true, force: true });
mkdirSync(outdir, { recursive: true });

await build({
  entryPoints: [join(root, 'src/cli/main.ts')],
  outfile: join(outdir, 'jourilo.mjs'),
  bundle: true,
  platform: 'node',
  target: 'node20',
  format: 'esm',
  minify: false,
  // keepNames would inject __name() calls into functions serialized into the page.
  keepNames: false,
  legalComments: 'eof',
  sourcemap: false,
  logLevel: 'warning',
  external: ['playwright-core'],
  plugins: [rawPlugin, tsParserChunk],
  define: { __JOURILO_VERSION__: JSON.stringify(pkg.version) },
  banner: {
    js: [
      '#!/usr/bin/env node',
      `// Jourilo ${pkg.version} - generated by scripts/build.mjs. Do not edit; edit src/ instead.`,
      "import { createRequire as __jouriloCreateRequire } from 'node:module';",
      'const require = __jouriloCreateRequire(import.meta.url);',
    ].join('\n'),
  },
});
console.log(`built ${join(outdir, 'jourilo.mjs')}`);

await build({
  entryPoints: [join(root, 'src/discovery/ast/parser.ts')],
  outfile: join(outdir, 'ts-parser.mjs'),
  bundle: true,
  platform: 'node',
  target: 'node20',
  format: 'esm',
  // Third-party code only (nothing is serialized into pages): minified to keep the package small.
  minify: true,
  keepNames: false,
  legalComments: 'eof',
  sourcemap: false,
  logLevel: 'warning',
  banner: {
    js: [
      `// Jourilo ${pkg.version} TypeScript parser chunk - generated by scripts/build.mjs. Do not edit.`,
      "import { createRequire as __jouriloCreateRequire } from 'node:module';",
      "import { fileURLToPath as __jouriloFileURLToPath } from 'node:url';",
      'const require = __jouriloCreateRequire(import.meta.url);',
      // TypeScript's node system reads these CommonJS globals when it loads.
      'const __filename = __jouriloFileURLToPath(import.meta.url);',
      "const __dirname = __jouriloFileURLToPath(new URL('.', import.meta.url));",
    ].join('\n'),
  },
});
console.log(`built ${join(outdir, 'ts-parser.mjs')}`);

// Bundled third-party code keeps its license next to the bundle (axe-core is MPL-2.0; its source is published at
// https://github.com/dequelabs/axe-core and in the npm package. TypeScript is Apache-2.0 and ships its own notices).
{
  const { copyFileSync, mkdirSync: mk } = await import('node:fs');
  mk(join(outdir, 'licenses'), { recursive: true });
  copyFileSync(
    join(root, 'node_modules', 'axe-core', 'LICENSE'),
    join(outdir, 'licenses', 'axe-core-LICENSE.txt'),
  );
  copyFileSync(
    join(root, 'node_modules', 'axe-core', 'LICENSE-3RD-PARTY.txt'),
    join(outdir, 'licenses', 'axe-core-LICENSE-3RD-PARTY.txt'),
  );
  copyFileSync(
    join(root, 'node_modules', 'typescript-js', 'LICENSE.txt'),
    join(outdir, 'licenses', 'typescript-LICENSE.txt'),
  );
  copyFileSync(
    join(root, 'node_modules', 'typescript-js', 'ThirdPartyNoticeText.txt'),
    join(outdir, 'licenses', 'typescript-ThirdPartyNoticeText.txt'),
  );
}

// Generated docs: the CLI reference comes from the command registry so docs and plugin never drift from code.
if (!process.argv[2]) {
  const { execFileSync } = await import('node:child_process');
  const { writeFileSync: write, mkdirSync: mkdir } = await import('node:fs');
  const md = execFileSync(process.execPath, [join(outdir, 'jourilo.mjs'), '__cli-markdown'], {
    encoding: 'utf8',
  });
  write(join(root, 'docs', 'CLI.md'), md);
  mkdir(join(root, 'plugin', 'skills', 'jourilo', 'references'), { recursive: true });
  write(join(root, 'plugin', 'skills', 'jourilo', 'references', 'cli.md'), md);
}
