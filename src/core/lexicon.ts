/**
 * Concepts matched as word stems (no trailing boundary): message and signal vocabulary must also match inflected
 * forms (Turkish "zorunlu-dur", "yorum-ları", German compounds). Actions stay whole words for precision.
 */
const STEMS = new Set<Concept>([
  'formError',
  'trustTestimonials',
  'trustGuarantee',
  'trustSecurity',
  'trustLogos',
  'freeTrial',
]);

/** Unicode-aware regex source for a concept (use with flags "iu"). */
export function lexiconSource(concept: Concept, opts: { exact?: boolean } = {}): string {
  const alt = LEX[concept].join('|');
  if (opts.exact) return `^\\s*(?:${alt})\\s*[.!…]?\\s*$`;
  return `(?<![\\p{L}\\p{N}])(?:${alt})${STEMS.has(concept) ? '' : '(?![\\p{L}\\p{N}])'}`;
}

/** Turkish fold: dotted capital İ -> i, plain capital I -> ı (dotless), then lower-cased. */
export function turkishFold(text: string): string {
  return text.replace(/İ/g, 'i').replace(/I/g, 'ı').toLowerCase();
}

/**
 * A case-insensitive regex whose test() also tries the Turkish fold of the text. Plain case-insensitive matching
 * maps I to i (right for English "LIGHT") but cannot match "KARANLIK" to "karanlık" or "DİL" to "dil", so both the
 * original text and its Turkish fold are tested.
 */
/** The Turkish fold applies only through `.test()`; `exec`, `match` and `replace` see the plain case-insensitive match. */
class LexiconRegExp extends RegExp {
  override test(text: string): boolean {
    return super.test(text) || super.test(turkishFold(text));
  }
}

export function lexicon(concept: Concept, opts: { exact?: boolean } = {}): RegExp {
  return new LexiconRegExp(lexiconSource(concept, opts), 'iu');
}

/** All concept sources, for code that runs inside the page (it receives plain strings). */
export function lexiconSources(): Record<Concept, string> {
  return Object.fromEntries(Object.keys(LEX).map((k) => [k, lexiconSource(k as Concept)])) as Record<
    Concept,
    string
  >;
}
