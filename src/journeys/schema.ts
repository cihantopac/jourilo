// Journey specification: a reusable, inspectable test scenario with explicit success criteria. Stored as JSON
// (.jourilo/journeys/<id>.json) so people can read, edit and review them like any other test.
import { JouriloError } from '../core/errors.js';

/** How a step finds its element. Prefer user-facing locators (role + name, label) over CSS. */
export type Target =
  | { role: string; name?: string; exact?: boolean }
  | { label: string; exact?: boolean }
  | { text: string; exact?: boolean }
  | { placeholder: string }
  | { testId: string }
  | { css: string };

export type Step =
  | { action: 'goto'; url: string; note?: string }
  | { action: 'click'; target: Target; note?: string }
  | { action: 'fill'; target: Target; value: string; note?: string }
  | { action: 'select'; target: Target; value: string; note?: string }
  | { action: 'check'; target: Target; note?: string }
  | { action: 'press'; key: string; target?: Target; note?: string }
  | { action: 'hover'; target: Target; note?: string }
  | { action: 'wait'; ms?: number; target?: Target; note?: string }
  | { action: 'back'; note?: string }
  | { action: 'expect'; url?: string; visible?: Target; hidden?: Target; title?: string; note?: string }
  | { action: 'screenshot'; name?: string; note?: string };

export interface SuccessCriterion {
  description: string;
  /** "/path" (exact path), "re:<regex>" or a substring the final URL must match. */
  url?: string;
  /** Same syntax as url; the final URL must NOT match (e.g. "left the form page"). */
  urlNot?: string;
  visible?: Target;
  /** The journey must finish without uncaught exceptions. */
  noPageErrors?: boolean;
  /** No first-party request may fail. */
  noFailedRequests?: boolean;
}

export interface JourneySpec {
  $schema?: string;
  version: 1;
  id: string;
  name: string;
  /** Why this journey matters (the user goal). */
  goal?: string;
  persona?: string;
  /** Path or absolute URL on the target origin. */
  start: string;
  viewport?: string;
  steps: Step[];
  success: SuccessCriterion[];
  /** Declares what the journey does so the safety policy can allow or block it up front. */
  safety?: { submitsForms?: boolean; destructive?: boolean };
  /** Where the journey came from: "suggested" (generated by Jourilo), "user", "agent". */
  source?: 'suggested' | 'user' | 'agent';
  tags?: string[];
}

const ACTIONS = new Set([
  'goto',
  'click',
  'fill',
  'select',
  'check',
  'press',
  'hover',
  'wait',
  'back',
  'expect',
  'screenshot',
]);
const NEEDS_TARGET = new Set(['click', 'fill', 'select', 'check', 'hover']);

function validTarget(t: unknown): t is Target {
  if (!t || typeof t !== 'object') return false;
  const o = t as Record<string, unknown>;
  const keys = ['role', 'label', 'text', 'placeholder', 'testId', 'css'].filter(
    (k) => typeof o[k] === 'string' && o[k],
  );
  return keys.length >= 1;
}

export function validateJourney(raw: unknown, source = 'journey'): JourneySpec {
  const errs: string[] = [];
  if (!raw || typeof raw !== 'object')
    throw new JouriloError('INVALID_INPUT', `${source}: not a JSON object.`);
  const j = raw as Partial<JourneySpec>;
  if (j.version !== 1) errs.push('version must be 1');
  if (!j.id || !/^[a-z0-9][a-z0-9-]{0,63}$/.test(j.id))
    errs.push('id must be lowercase letters, digits and dashes');
  if (!j.name) errs.push('name is required');
  if (!j.start || typeof j.start !== 'string') errs.push('start (path or URL) is required');
  if (!Array.isArray(j.steps) || !j.steps.length) errs.push('steps must be a non-empty array');
  if (!Array.isArray(j.success) || !j.success.length)
    errs.push('success must list at least one explicit criterion');
  (j.steps ?? []).forEach((s, i) => {
    const step = s as Step & { target?: unknown; value?: unknown };
    if (!step || !ACTIONS.has(step.action))
      errs.push(`steps[${i}]: unknown action "${(step as { action?: string })?.action}"`);
    else if (NEEDS_TARGET.has(step.action) && !validTarget(step.target))
      errs.push(`steps[${i}] (${step.action}): target is required`);
    else if ((step.action === 'fill' || step.action === 'select') && typeof step.value !== 'string')
      errs.push(`steps[${i}] (${step.action}): value must be a string`);
    else if (step.action === 'goto' && typeof (step as { url?: unknown }).url !== 'string')
      errs.push(`steps[${i}] (goto): url is required`);
    else if (step.action === 'press' && typeof (step as { key?: unknown }).key !== 'string')
      errs.push(`steps[${i}] (press): key is required`);
  });
  (j.success ?? []).forEach((c, i) => {
    if (!c?.description) errs.push(`success[${i}]: description is required`);
    if (c && !c.url && !c.urlNot && !c.visible && !c.noPageErrors && !c.noFailedRequests)
      errs.push(`success[${i}]: needs url, urlNot, visible, noPageErrors or noFailedRequests`);
    if (c?.visible && !validTarget(c.visible)) errs.push(`success[${i}]: visible must be a target`);
  });
  if (errs.length)
    throw new JouriloError('INVALID_INPUT', `${source} is invalid:\n  - ${errs.join('\n  - ')}`);
  return j as JourneySpec;
}

export function describeTarget(t: Target): string {
  if ('role' in t) return `${t.role}${t.name ? ` "${t.name}"` : ''}`;
  if ('label' in t) return `field labelled "${t.label}"`;
  if ('text' in t) return `text "${t.text}"`;
  if ('placeholder' in t) return `field with placeholder "${t.placeholder}"`;
  if ('testId' in t) return `test id "${t.testId}"`;
  return `\`${t.css}\``;
}

export function describeStep(s: Step, secret = false): string {
  switch (s.action) {
    case 'goto':
      return `Go to ${s.url}`;
    case 'click':
      return `Click ${describeTarget(s.target)}`;
    case 'fill':
      return `Type ${secret ? '••••••' : `"${s.value}"`} into ${describeTarget(s.target)}`;
    case 'select':
      return `Choose "${s.value}" in ${describeTarget(s.target)}`;
    case 'check':
      return `Check ${describeTarget(s.target)}`;
    case 'press':
      return `Press ${s.key}${s.target ? ` in ${describeTarget(s.target)}` : ''}`;
    case 'hover':
      return `Hover ${describeTarget(s.target)}`;
    case 'wait':
      return s.target ? `Wait for ${describeTarget(s.target)}` : `Wait ${s.ms ?? 500} ms`;
    case 'back':
      return 'Go back';
    case 'expect':
      return `Expect ${[s.url ? `URL ~ ${s.url}` : '', s.visible ? `${describeTarget(s.visible)} visible` : '', s.hidden ? `${describeTarget(s.hidden)} hidden` : '', s.title ? `title ~ "${s.title}"` : ''].filter(Boolean).join(', ')}`;
    case 'screenshot':
      return `Screenshot${s.name ? ` "${s.name}"` : ''}`;
  }
}
