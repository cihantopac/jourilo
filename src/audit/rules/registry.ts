// The machine-readable list of every rule Jourilo can report (`jourilo rules list --json`). One row per native rule;
// `axe/<id>` and `axe-review/<id>` rules come from axe-core's own rule list (see src/cli/commands/rules.ts).
// tests/unit/rule-registry.test.ts fails when a rule id is emitted by the code but missing here, or listed here but
// never emitted.
import type { Category, FindingKind, Severity } from '../../core/types.js';

export interface RuleInfo {
  id: string;
  category: Category;
  /** The severity the rule reports, or 'varies' when it depends on what was measured. */
  severity: Severity | 'varies';
  kind: FindingKind;
  title: string;
  /** Standards the rule cites, e.g. "WCAG 2.2 2.4.7". Empty for rules that cite none. */
  standards: string[];
}

function rule(
  id: string,
  category: Category,
  kind: FindingKind,
  severity: Severity | 'varies',
  title: string,
  standards: string[],
): RuleInfo {
  return { id, category, severity, kind, title, standards };
}

