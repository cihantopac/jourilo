export const I18N: Record<Lang, Record<MsgKey, string>> = { en: EN, tr: TR };

export type Vars = Record<string, string | number>;

export function fill(template: string, vars: Vars = {}): string {
  return template.replace(/\{(\w+)(:s)?\}/g, (_m, k: string, plural?: string) => {
    const v = vars[k];
    if (plural) return Number(v) === 1 ? '' : 's';
    return v === undefined ? '' : String(v);
  });
}
